/**
 * Sanzo Wada's 348 colour combinations as a shelf an agent can read.
 *
 * `palettes/wada/colors.json` is the open dataset from mattdesl/dictionary-of-colour-combinations
 * (MIT): 159 colours, each with the numbers of the combinations it appears in. Nothing reads a
 * combination by number in that shape, so this module inverts it and writes
 * `palettes/wada/combinations.md`, one line per combination.
 *
 * Each line carries three tags computed from the colours' Lab values. They approximate the
 * distinctions Wada draws in his preface — same-tone against contrast-tone harmony, light
 * against dark, soft against strong — but they are measurements, not his labels, and the
 * thresholds are hand-set. The best text pair is there because the book shows colours as equal
 * swatches, and a page needs to know before choosing whether any two of them can carry text.
 */

import fs from 'node:fs';
import path from 'node:path';

/** Below this chroma a colour counts as a neutral and has no hue worth comparing. Wada's
 * greyed colours (Glaucous Green, chroma 9) still read as hued, so the bar is low. */
const NEUTRAL_CHROMA = 6;

export function readWada(dir) {
  const colors = JSON.parse(fs.readFileSync(path.join(dir, 'colors.json'), 'utf8'));
  const byId = new Map();
  for (const color of colors) {
    for (const id of color.combinations) {
      if (!byId.has(id)) byId.set(id, []);
      byId.get(id).push(color);
    }
  }
  const combinations = [...byId.entries()].sort((a, b) => a[0] - b[0]).map(([id, members]) => ({ id, colors: members }));
  return { colors, combinations };
}

const chroma = ([, a, b]) => Math.hypot(a, b);
const hue = ([, a, b]) => ((Math.atan2(b, a) * 180) / Math.PI + 360) % 360;

function luminance([r, g, b]) {
  const lin = (v) => {
    const c = v / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
}

export function contrast(rgb1, rgb2) {
  const [hi, lo] = [luminance(rgb1), luminance(rgb2)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

/** The tags and best text pair for one combination. */
export function describe(combination) {
  const labs = combination.colors.map((c) => c.lab);
  const lightness = labs.map((l) => l[0]);
  const mean = lightness.reduce((s, l) => s + l, 0) / lightness.length;
  const value = Math.max(...lightness) - Math.min(...lightness) >= 40 ? 'light-and-dark'
    : mean >= 65 ? 'light' : mean <= 40 ? 'dark' : 'mid';
  const chromas = labs.map(chroma);
  const strength = Math.max(...chromas) < 25 ? 'soft' : Math.max(...chromas) > 60 ? 'strong' : 'moderate';
  const hues = labs.filter((l) => chroma(l) >= NEUTRAL_CHROMA).map(hue);
  let spread = 0;
  for (const h1 of hues) {
    for (const h2 of hues) {
      const d = Math.abs(h1 - h2);
      spread = Math.max(spread, Math.min(d, 360 - d));
    }
  }
  const harmony = hues.length < 2 ? 'neutral-led' : spread <= 45 ? 'same-tone' : 'contrast-tone';
  let best = null;
  for (const a of combination.colors) {
    for (const b of combination.colors) {
      if (a === b) continue;
      const ratio = contrast(a.rgb, b.rgb);
      if (!best || ratio > best.ratio) best = { ratio, pair: [a, b].sort((x, y) => luminance(x.rgb) - luminance(y.rgb)) };
    }
  }
  return { harmony, value, strength, best };
}

const pad = (n) => String(n).padStart(3, '0');

export function indexMarkdown({ combinations }) {
  const lines = combinations.map((combination) => {
    const { harmony, value, strength, best } = describe(combination);
    const colors = combination.colors.map((c) => `${c.name} ${c.hex}`).join(' + ');
    const [dark, light] = best.pair;
    return `- ${pad(combination.id)} (${combination.colors.length}) ${colors} · ${harmony}, ${value}, ${strength}`
      + ` · text: ${dark.name} on ${light.name} ${best.ratio.toFixed(1)}:1`;
  });
  return [
    '# Wada colour combinations',
    '',
    `Generated by \`npm run sync\` from colors.json (${combinations.length} combinations). Do not hand-edit.`,
    'Each line: number (colours in it) colours with hex · computed harmony, value and strength · the',
    'highest-contrast pair in it, darker on lighter. Text needs 4.5:1 (3:1 at 24px, or 18.7px bold).',
    '',
    ...lines,
    '',
  ].join('\n');
}

/** @returns {{path: string, changed: boolean}} */
export function writeIndex(dir) {
  const file = path.join(dir, 'combinations.md');
  const next = indexMarkdown(readWada(dir));
  const previous = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (previous === next) return { path: file, changed: false };
  fs.writeFileSync(file, next);
  return { path: file, changed: true };
}
