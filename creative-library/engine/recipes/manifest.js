/**
 * Generates recipes/web/manifest.json from the `UI.define()` calls in recipes/web/*.js.
 *
 * PLAN.md phase 5.3 asks for the manifest to be generated from source "rather than hand-
 * maintaining it", because ui-master shipped two hand-maintained component-manifest.json
 * copies that had drifted apart — the React one claimed six components while its
 * components/ directory held one file, and the vanilla one claimed three.
 *
 * The modules are loaded in a real browser rather than parsed or run in a stubbed
 * sandbox. A spec is only reachable by executing the file, and executing it in Chromium
 * is the same thing as proving it loads: a recipe with a syntax error, a missing global,
 * or a top-level throw cannot appear in the manifest. Static parsing would happily list a
 * component that crashes on first use, which for a library whose entire promise is
 * "verified code to copy" would be the one failure mode that matters.
 *
 * `three-scene` declares a dependency on a CDN-hosted global (THREE). It is loaded with
 * that global stubbed absent — `UI.define` still runs, since the define call is at module
 * scope and only `mount()` touches THREE. So the manifest records the recipe and its
 * `requires`, without this generator needing network access.
 */

import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright';

/** Load order matters: registry.js must define window.UI before any component registers. */
const REGISTRY = 'registry.js';

/** @returns {string[]} component filenames, registry first, then the rest alphabetically. */
export function recipeFiles(recipesDir) {
  const files = fs
    .readdirSync(recipesDir)
    .filter((f) => f.endsWith('.js'))
    .sort();
  if (!files.includes(REGISTRY)) {
    throw new Error(`${recipesDir}: no ${REGISTRY} — nothing can register without it`);
  }
  return [REGISTRY, ...files.filter((f) => f !== REGISTRY)];
}

/**
 * @param {string} recipesDir Absolute path to recipes/web.
 * @returns {Promise<{library: string, components: object[]}>}
 */
export async function buildManifest(recipesDir) {
  const files = recipeFiles(recipesDir);
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage();
    const failures = [];
    page.on('pageerror', (err) => failures.push(err.message));

    await page.setContent('<!doctype html><html lang="en"><body></body></html>');
    for (const file of files) {
      await page.addScriptTag({ content: fs.readFileSync(path.join(recipesDir, file), 'utf8') });
    }

    if (failures.length > 0) {
      throw new Error(`recipe modules threw while loading:\n  ${failures.join('\n  ')}`);
    }

    const components = await page.evaluate(() => window.UI.manifest());
    const registered = new Set(components.map((c) => c.id));
    const expected = files.filter((f) => f !== REGISTRY).map((f) => f.replace(/\.js$/, ''));
    const silent = expected.filter((id) => !registered.has(id));
    if (silent.length > 0) {
      // A file that loads without registering is the drift this command exists to stop:
      // it looks present on disk and is invisible to everything downstream.
      throw new Error(`loaded but never called UI.define(): ${silent.join(', ')}`);
    }

    return {
      library: 'creative-library web recipes',
      description:
        'Generated by `npm run sync` from the UI.define() calls in recipes/web/*.js. Do not hand-edit.',
      components,
    };
  } finally {
    await browser.close();
  }
}

/** @returns {{path: string, changed: boolean}} */
export async function writeManifest(recipesDir) {
  const manifest = await buildManifest(recipesDir);
  const file = path.join(recipesDir, 'manifest.json');
  const next = JSON.stringify(manifest, null, 2) + '\n';
  const previous = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (previous === next) return { path: file, changed: false };
  fs.writeFileSync(file, next);
  return { path: file, changed: true };
}

/** Reads the committed manifest. Returns null when it has never been generated. */
export function readManifest(recipesDir) {
  const file = path.join(recipesDir, 'manifest.json');
  if (!fs.existsSync(file)) return null;
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}
