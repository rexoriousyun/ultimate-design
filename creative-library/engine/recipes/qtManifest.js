/**
 * Generates recipes/qt/manifest.json from the `RECIPE` dict in each recipes/qt/*.py.
 *
 * Same contract as the web generator (engine/recipes/manifest.js) and for the same reason:
 * the manifest is derived from the modules rather than hand-maintained, so a recipe that
 * does not import cannot appear in it and a deleted file disappears on the next sync.
 *
 * The modules are imported in a real Python interpreter rather than parsed. A recipe whose
 * `RECIPE` dict is computed from module state — `icon.py` builds its `props.name.values`
 * from `ICONS.keys()` — cannot be read statically without reimplementing Python, and a
 * library whose whole promise is "this code works" should be proven to at least import.
 *
 * PyQt6 is deliberately NOT imported here. `icon.py` keeps its Qt imports inside the
 * functions that need them precisely so its spec can be read on a machine with no Qt
 * installed; hoisting them to module scope would make the manifest un-generatable in CI.
 */

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

/** @returns {string[]} recipe module filenames, alphabetically. */
export function qtRecipeFiles(recipesDir) {
  if (!fs.existsSync(recipesDir)) return [];
  return fs
    .readdirSync(recipesDir)
    .filter((f) => f.endsWith('.py') && !f.startsWith('_'))
    .sort();
}

const READER = `
import importlib.util, json, sys, pathlib


# The recipes directory goes on sys.path so a recipe can import a sibling recipe, which is how
# a Qt project actually holds them: recipes are copied, not imported across a package
# boundary, so acorn_hoard.py and pixel_sprite.py sit in the same folder. Loading purely by
# file path left siblings unimportable — caught by the render gate the moment acorn_hoard
# arrived, with "No module named 'pixel_sprite'".
sys.path.insert(0, str(pathlib.Path(sys.argv[1]).resolve()))

out = []
problems = []
for p in sorted(pathlib.Path(sys.argv[1]).glob("*.py")):
    if p.name.startswith("_"):
        continue
    spec = importlib.util.spec_from_file_location(p.stem, p)
    module = importlib.util.module_from_spec(spec)
    try:
        spec.loader.exec_module(module)
    except Exception as exc:
        problems.append("%s failed to import: %s" % (p.name, exc))
        continue
    recipe = getattr(module, "RECIPE", None)
    if recipe is None:
        problems.append("%s defines no RECIPE dict" % p.name)
        continue
    out.append(recipe)

print(json.dumps({"components": sorted(out, key=lambda c: c.get("id", "")), "problems": problems}))
`;

/**
 * @param {string} recipesDir Absolute path to recipes/qt.
 * @returns {{library: string, description: string, components: object[]}}
 */
export function buildQtManifest(recipesDir) {
  const files = qtRecipeFiles(recipesDir);
  if (files.length === 0) {
    return {
      library: 'creative-library Qt recipes',
      description: 'Generated by `npm run sync` from the RECIPE dict in recipes/qt/*.py. Do not hand-edit.',
      components: [],
    };
  }

  const raw = execFileSync('python3', ['-c', READER, recipesDir], { encoding: 'utf8' });
  const { components, problems } = JSON.parse(raw);
  if (problems.length > 0) {
    throw new Error(`Qt recipe modules could not be read:\n  ${problems.join('\n  ')}`);
  }

  return {
    library: 'creative-library Qt recipes',
    description: 'Generated by `npm run sync` from the RECIPE dict in recipes/qt/*.py. Do not hand-edit.',
    components,
  };
}

/** @returns {{path: string, changed: boolean}} */
export function writeQtManifest(recipesDir) {
  const manifest = buildQtManifest(recipesDir);
  const file = path.join(recipesDir, 'manifest.json');
  const next = JSON.stringify(manifest, null, 2) + '\n';
  const previous = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (previous === next) return { path: file, changed: false };
  fs.mkdirSync(recipesDir, { recursive: true });
  fs.writeFileSync(file, next);
  return { path: file, changed: true };
}

export function readQtManifest(recipesDir) {
  const file = path.join(recipesDir, 'manifest.json');
  if (!fs.existsSync(file)) return null;
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}
