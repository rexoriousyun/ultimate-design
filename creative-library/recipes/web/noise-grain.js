/**
 * Film-grain / paper-tooth texture — an SVG filter that generates its own noise.
 *
 * The reason this is worth a recipe: the usual way to get grain is a tiled PNG, which costs a
 * network request, cannot change density without a new asset, and looks wrong on a display
 * whose devicePixelRatio it was not baked for. feTurbulence generates the noise in the
 * renderer at whatever resolution the element is actually painted at, so it is resolution
 * independent and weighs nothing.
 *
 * Three primitives, in order, and each is load-bearing:
 *   feTurbulence   — fractalNoise, which is the smooth kind; type="turbulence" gives you
 *                    veiny plasma, not grain.
 *   feColorMatrix  — collapses the noise to greyscale. Skipping this is the single most
 *                    common mistake: raw feTurbulence is *colour* noise, and overlaying it
 *                    tints everything underneath in rainbow speckle.
 *   feComponentTransfer — pulls the alpha down to the intended opacity, so the grain sits
 *                    over the content instead of replacing it.
 *
 * This is a texture, so it is decorative by definition: the <svg> is aria-hidden and
 * pointer-events:none. A texture that swallows clicks is a bug, and one that a screen reader
 * reads out is noise in the other sense.
 *
 * It does not animate, which is why there is no prefers-reduced-motion branch here — static
 * grain is exactly what you want; animated grain is a seizure risk and a battery cost.
 *
 * Usage: container.innerHTML = UINoiseGrain.overlay({ opacity: 0.22 });
 * Requires recipes/web/registry.js loaded first.
 */
(function (global) {
  let seq = 0;

  /**
   * A full-bleed grain layer to drop inside a positioned container.
   * @param {object} [opts] baseFrequency, opacity, numOctaves, blend
   * @returns {string} a complete <svg> string, absolutely positioned.
   */
  function overlay(opts) {
    const o = opts || {};
    const baseFrequency = o.baseFrequency == null ? 0.8 : o.baseFrequency;
    const numOctaves = o.numOctaves == null ? 4 : o.numOctaves;
    const opacity = o.opacity == null ? 0.22 : o.opacity;
    const blend = o.blend || 'multiply';
    const id = 'grain-' + ++seq;

    return (
      '<svg aria-hidden="true" focusable="false"' +
        ' style="position:absolute;inset:0;width:100%;height:100%;pointer-events:none;' +
          'mix-blend-mode:' + blend + '">' +
        '<filter id="' + id + '">' +
          '<feTurbulence type="fractalNoise" baseFrequency="' + baseFrequency + '"' +
            ' numOctaves="' + numOctaves + '" stitchTiles="stitch"/>' +
          // Luminance-to-grey. Without it the noise is coloured and tints the content.
          '<feColorMatrix type="saturate" values="0"/>' +
          '<feComponentTransfer>' +
            '<feFuncA type="linear" slope="' + opacity + '"/>' +
          '</feComponentTransfer>' +
        '</filter>' +
        '<rect width="100%" height="100%" filter="url(#' + id + ')"/>' +
      '</svg>'
    );
  }

  global.UINoiseGrain = { overlay };

  if (global.UI) {
    function swatch(props) {
      const p = props || {};
      return (
        '<div style="position:relative;overflow:hidden;border-radius:10px;height:190px;' +
          'background:linear-gradient(135deg,#1f3d2b,#4a7c59 55%,#c9d8c5)">' +
          '<p style="position:relative;z-index:1;margin:0;padding:1rem;color:#ffffff;' +
            'font-weight:600;font-size:1.1rem">Grain over a gradient</p>' +
          overlay({
            baseFrequency: p.baseFrequency, opacity: p.opacity,
            numOctaves: p.numOctaves, blend: p.blend,
          }) +
        '</div>'
      );
    }

    global.UI.define({
      id: 'noise-grain',
      primitive: 'svg',
      label: 'Noise grain',
      source: 'recipes/web/noise-grain.js',
      export: 'UINoiseGrain',
      description:
        'Resolution-independent film grain from feTurbulence — no tiled PNG, no extra request.',
      props: {
        baseFrequency: {
          type: 'number', default: 0.8,
          controls: 'Grain size: high is fine film grain, low is blotchy paper tooth.',
          range: [0.2, 1.2], sweep: [0.2, 0.4, 0.8, 1.2],
          cost: 'none — generated by the renderer at paint resolution',
        },
        opacity: {
          type: 'number', default: 0.22,
          controls: 'How strongly the grain shows. Keep it subtle: grain should be felt before it is seen.',
          range: [0.05, 0.6], sweep: [0.05, 0.11, 0.22, 0.4, 0.6],
          breaks: { below: 'Swept: under ~0.11 the grain changes no pixel by more than 4/255 on this swatch; it is invisible, not subtle.' },
          cost: 'none',
        },
        numOctaves: {
          type: 'number', default: 4,
          controls: 'Layers of finer detail on top of the base grain. Only the second octave is visible, and only on coarse texture: 1 is smooth mottling, 2 adds tooth. At the default fine grain no octave step changes anything.',
          range: [1, 2], sweep: [1, 2, 3, 4],
          breaks: { above: 'Swept: past 2 octaves the added detail is below a pixel even on coarse grain (0.05); 3 and 4 only cost more.' },
          // Swept on coarse, strong grain: at the defaults (0.8, 0.22) every octave step is 0.0%.
          sweepWith: { baseFrequency: 0.05, opacity: 0.6 },
          cost: 'grows with octaves',
        },
        blend: {
          type: 'enum', values: ['multiply', 'overlay', 'soft-light', 'normal'], default: 'multiply',
          controls: 'How grain combines with what is under it: multiply darkens (paper), overlay and soft-light keep contrast (film), normal lays grey over it.',
          sweep: ['multiply', 'overlay', 'soft-light', 'normal'],
          cost: 'none',
        },
      },
      signature: {
        within: 'filter',
        // Deliberately narrower than squiggle-wobble's, which is turbulence + displacement.
        // The desaturating colour matrix is what makes this grain rather than distortion.
        requires: ['feTurbulence[type="fractalNoise"]', 'feColorMatrix[type="saturate"]'],
        why: 'fractal noise desaturated to grey and used as a layer is the grain recipe',
      },
      snippet:
        "// container must be position:relative — the overlay is absolutely positioned.\ncontainer.insertAdjacentHTML(\n  'beforeend',\n  UINoiseGrain.overlay({ baseFrequency: 0.8, opacity: 0.22 })\n);",
      preview(container, props) {
        container.innerHTML = swatch(props);
        return { destroy() { container.innerHTML = ''; } };
      },
      demo(container) {
        const stage = document.createElement('div');
        const controls = document.createElement('div');
        controls.className = 'ui-demo-controls';
        controls.innerHTML =
          '<button class="ui-demo-ctl" data-o="0" >None</button>' +
          '<button class="ui-demo-ctl" data-o="0.22" aria-pressed="true">Subtle</button>' +
          '<button class="ui-demo-ctl" data-o="0.6">Heavy</button>';

        function draw(opacity) {
          stage.innerHTML = swatch({ opacity: opacity });
        }

        controls.addEventListener('click', function (e) {
          const o = e.target.dataset && e.target.dataset.o;
          if (o == null) return;
          draw(Number(o));
          controls.querySelectorAll('.ui-demo-ctl').forEach(function (b) {
            b.setAttribute('aria-pressed', b.dataset.o === o ? 'true' : 'false');
          });
        });

        container.appendChild(controls);
        container.appendChild(stage);
        draw(0.22);
        return { destroy() { stage.innerHTML = ''; } };
      },
    });
  }
})(window);
